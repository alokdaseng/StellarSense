class AerospaceToolExecutor:
    """Safely executes tool calls generated by the Gemma 4 Model Harness."""

    def __init__(self, serial_transmitter=None):
        self.serial_transmitter = serial_transmitter
        self.action_history: List[Dict[str, Any]] = []

    def execute_tool(self, tool_name: str, arguments: Dict[str, Any]) -> Dict[str, Any]:
        """Dispatches and validates tool execution."""
        timestamp = time.strftime("%H:%M:%S")

        if tool_name == "uplink_telecommand":
            cmd = arguments.get("command", "").strip()
            rationale = arguments.get("rationale", "No rationale provided")

            if cmd not in VALID_COMMANDS:
                result = {
                    "status": "REJECTED",
                    "reason": f"Unknown telecommand '{cmd}'. Allowed: {list(VALID_COMMANDS.keys())}",
                    "timestamp": timestamp
                }
            else:
                dispatched = False
                if self.serial_transmitter and callable(self.serial_transmitter):
                    try:
                        self.serial_transmitter(cmd)
                        dispatched = True
                    except Exception as err:
                        dispatched = False

                result = {
                    "status": "EXECUTED",
                    "command": cmd,
                    "description": VALID_COMMANDS[cmd],
                    "rationale": rationale,
                    "dispatched_to_rf": dispatched,
                    "timestamp": timestamp
                }

            self.action_history.append({"tool": tool_name, "args": arguments, "result": result})
            return result

        elif tool_name == "emit_fdir_diagnosis":
            diagnosis = {
                "status": "PUBLISHED",
                "subsystem": arguments.get("subsystem", "System Wide"),
                "severity": arguments.get("severity", "NOMINAL"),
                "root_cause": arguments.get("root_cause", "Telemetry metrics within nominal bounds."),
                "confidence_pct": round(float(arguments.get("confidence_pct", 95.0)), 1),
                "recommended_action": arguments.get("recommended_action", "Continue nominal mission operations."),
                "timestamp": timestamp
            }
            self.action_history.append({"tool": tool_name, "args": arguments, "result": diagnosis})
            return diagnosis

        else:
            return {
                "status": "ERROR",
                "reason": f"Unrecognized tool '{tool_name}'",
                "timestamp": timestamp
            }

